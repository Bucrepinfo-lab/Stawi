#!/usr/bin/env bash
# Stawi — Cloud Agent install phase (durable, idempotent).
#
# Runs once after checkout (and once per environment build to bake the base
# snapshot). Installs the JS dependencies + Prisma client, provisions a local
# PostgreSQL for the DB-backed dev experience, and seeds a demo tenant so the
# web app persists reads/writes out of the box. The app still runs in seed
# mode if the DB is ever unavailable, so nothing here is load-bearing for a
# read-only demo.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

DB_URL="postgresql://stawi:stawi@localhost:5432/stawi?schema=public"

echo "==> Installing system PostgreSQL (if missing)"
if ! command -v pg_ctlcluster >/dev/null 2>&1; then
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq postgresql postgresql-contrib
fi

echo "==> Starting PostgreSQL cluster"
sudo pg_ctlcluster 16 main start 2>/dev/null || true
# Wait until the server accepts connections.
for _ in $(seq 1 30); do
  if sudo -u postgres pg_isready -q 2>/dev/null; then break; fi
  sleep 1
done

echo "==> Ensuring stawi role + database"
sudo -u postgres psql -v ON_ERROR_STOP=1 -c \
  "DO \$\$ BEGIN IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname='stawi') THEN CREATE ROLE stawi LOGIN PASSWORD 'stawi'; END IF; END \$\$;"
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='stawi'" | grep -q 1 \
  || sudo -u postgres createdb -O stawi stawi

echo "==> Installing JS dependencies (npm ci)"
npm ci

echo "==> Generating Prisma client"
npm run generate --workspace @stawi/db

echo "==> Applying schema to the database (prisma db push)"
DATABASE_URL="$DB_URL" npm run --workspace @stawi/db push

echo "==> Applying row-level-security policies"
PGPASSWORD=stawi psql -h localhost -U stawi -d stawi -f packages/db/prisma/rls.sql >/dev/null 2>&1 || true

echo "==> Seeding demo data (only if the database is empty)"
COUNT="$(PGPASSWORD=stawi psql -h localhost -U stawi -d stawi -tAc 'SELECT count(*) FROM "Tenant";' 2>/dev/null || echo 0)"
if [ "${COUNT:-0}" = "0" ]; then
  DATABASE_URL="$DB_URL" npm run --workspace @stawi/db seed
else
  echo "    (Tenant rows already present: $COUNT — skipping seed)"
fi

echo "==> Writing apps/web/.env.local (local dev placeholders — not committed)"
# These are non-functional placeholders so the app boots and serves public
# pages + seeded data. Replace with real Supabase keys to exercise phone-OTP
# auth and the authenticated dashboard/cockpit.
cat > apps/web/.env.local <<'ENVEOF'
# Auto-generated by .cursor/install.sh for local Cloud Agent dev. Not committed.
DATABASE_URL="postgresql://stawi:stawi@localhost:5432/stawi?schema=public"
NEXT_PUBLIC_SUPABASE_URL="https://demo-project.supabase.co"
NEXT_PUBLIC_SUPABASE_ANON_KEY="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJyb2xlIjoiYW5vbiIsImlzcyI6InN1cGFiYXNlIn0.demo-placeholder"
NEXT_PUBLIC_APP_URL="http://localhost:3000"
NODE_ENV="development"
ENVEOF

echo "==> Install phase complete"
